import { readFileSync, writeFileSync } from 'node:fs';
const args = process.argv.slice(2);
const get = (name, fallback) => { const i = args.indexOf(name); if (i < 0) return fallback; if (!args[i + 1] || args[i + 1].startsWith('--')) throw new Error(`Valeur manquante : ${name}`); return args[i + 1]; };
const known = ['--env', '--config', '--from', '--test-to', '--host'];
for (let i = 0; i < args.length; i += 2) if (!known.includes(args[i])) throw new Error(`Argument inconnu : ${args[i]}`);
const target = get('--env', 'staging');
if (!['staging', 'production'].includes(target)) throw new Error('Environnement invalide.');
const path = get('--config', new URL('../wrangler.jsonc', import.meta.url));
const config = JSON.parse(readFileSync(path, 'utf8'));
const section = target === 'staging' ? config.env?.staging : config;
if (!section) throw new Error('La section staging est absente.');
const from = get('--from', 'contact@fcescalquens.fr');
const testTo = get('--test-to', 'contact@fcescalquens.fr');
const host = get('--host', 'ssl0.ovh.net');
const valid = value => /^[a-z0-9.!#$%&'*+/=?^_`{|}~-]+@[a-z0-9.-]+\.[a-z]{2,}$/i.test(value) && value.length <= 254;
if (!valid(from) || !valid(testTo)) throw new Error('Adresse e-mail invalide.');
if (!['ssl0.ovh.net', 'smtp.mail.ovh.net'].includes(host)) throw new Error('Serveur SMTP OVH non autorisé.');
section.vars = { ...section.vars, MAIL_PROVIDER: 'ovh', MAIL_FROM: from, MAIL_TEST_TO: testTo, SMTP_HOST: host, SMTP_USER: from };
writeFileSync(path, JSON.stringify(config, null, 2) + '\n');
console.log(`SMTP OVH configuré pour ${target}. Expéditeur : ${from}. Test : ${testTo}. Aucun secret enregistré. Ajoutez SMTP_PASSWORD dans les secrets du Worker. Les autres paramètres et bindings sont conservés.`);
